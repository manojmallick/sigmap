'use strict';

/**
 * callgraph-accuracy-doc.mjs — the numeric tables of docs-vp/guide/callgraph-accuracy.md, rendered
 * from benchmarks/reports/callgraph-accuracy.json (#976). The page holds this block between two
 * markers and a test regenerates it from the saved report, so a figure on the page cannot differ
 * from the report it quotes. Prose around the block says what the figures mean.
 *
 * Dev-only. Nothing here ships in the npm package.
 */

export const BEGIN = '<!-- callgraph-accuracy:begin (generated by scripts/run-callgraph-accuracy.mjs --write-doc; do not edit) -->';
export const END = '<!-- callgraph-accuracy:end -->';

const LABELS = { typescript: 'TypeScript', javascript: 'JavaScript', python: 'Python', go: 'Go', java: 'Java' };
const ORDER = ['typescript', 'javascript', 'python', 'go', 'java'];
const n0 = (n) => n.toLocaleString('en-US');
const pct = (v) => `${(100 * v).toFixed(1)}%`;

/** `13.0% (8-22)`; `n=2` when the cell has too few edges to quote; `-` when empty. */
export function cell(c, { band = true } = {}) {
  if (!c || c.value === null || c.value === undefined) return '-';
  if (c.small) return `n=${n0(c.n)}, too few`;
  const interval = band && c.lo !== null && c.hi !== null ? ` (${Math.round(100 * c.lo)}-${Math.round(100 * c.hi)})` : '';
  return `${pct(c.value)}${interval}`;
}

const rowOf = (g, label) => g.table.rows.find((r) => r.label === label);
const siteOf = (g, label) => g.table.sites.find((r) => r.label === label);
const groupsOf = (report) => ORDER.filter((k) => report.groups[k]);

/** A markdown table from a header row and body rows. */
function table(head, rows, align = []) {
  const sep = head.map((_, i) => (align[i] === 'l' || (i === 0 && !align.length) ? '---' : '---:'));
  return [`| ${head.join(' | ')} |`, `|${sep.join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
}

function headline(report) {
  const rows = groupsOf(report).map((k) => {
    const g = report.groups[k];
    const all = rowOf(g, 'all edges');
    const fn = rowOf(g, 'function');
    return [
      `**${LABELS[k]}**`, g.repos.join(', '), n0(all.recall.n),
      cell(all.recall), cell(fn.recall), cell(g.table.receiverOnly),
      cell(all.precision), cell(rowOf(g, 'judgeable edges').precision),
    ];
  });
  return table(
    ['Language', 'Repositories', 'Reference edges', 'Recall, all edges', 'Recall, function edges', 'Recall, method edges through a receiver', 'Precision', 'Precision, judgeable edges'],
    rows, ['l', 'l'],
  );
}

function perRepo(report) {
  const rows = [];
  for (const k of ORDER) {
    for (const [name, r] of Object.entries(report.repos[k] || {})) {
      if (r.status !== 'measured') {
        rows.push([LABELS[k], name, 'unmeasured', '', '', '', '', r.reason.length > 110 ? `${r.reason.slice(0, 107)}...` : r.reason]);
        continue;
      }
      const s = r.summary;
      rows.push([LABELS[k], name, n0(s.referenceEdges), n0(s.graphEdges), s.recall === null ? '-' : pct(s.recall), s.functionRecall === null ? '-' : pct(s.functionRecall), s.precision === null ? '-' : pct(s.precision), s.judgeablePrecision === null ? '-' : pct(s.judgeablePrecision)]);
    }
  }
  return table(['Language', 'Repository', 'Reference edges', 'Graph edges', 'Recall', 'Function recall', 'Precision', 'Judgeable precision'], rows, ['l', 'l']);
}

function bySite(report) {
  const ks = ['function/bare', 'function/qualified', 'method/bare', 'method/self', 'method/receiver', 'constructor/bare', 'constructor/qualified'];
  const groups = groupsOf(report);
  const rows = ks.map((label) => [`\`${label}\``, ...groups.map((k) => {
    const s = siteOf(report.groups[k], label);
    return s && s.recall.n ? cell(s.recall, { band: false }) + (s.recall.small ? '' : ` (n=${n0(s.recall.n)})`) : '-';
  })]);
  return table(['Edge kind / call site', ...groups.map((k) => LABELS[k])], rows);
}

const MISSED = [
  ['caller-not-a-graph-node', 'the graph has no node for the caller'],
  ['callee-not-a-graph-node', 'the graph has no node for the callee'],
  ['every-call-site-masked-by-graph', 'every call site is inside a string, template literal or comment the graph masks'],
  ['call-not-seen-same-file', 'both nodes exist, same file, call not seen'],
  ['call-not-linked-cross-file', 'both nodes exist, other file, call not linked'],
];

function missed(report) {
  const groups = groupsOf(report);
  const rows = MISSED.map(([id, text]) => [text, ...groups.map((k) => {
    const m = report.groups[k].diagnostics.missedByReason['function/bare'] || {};
    return m[id] ? n0(m[id]) : '0';
  })]);
  rows.push(['**missed `function/bare` edges**', ...groups.map((k) => {
    const m = report.groups[k].diagnostics.missedByReason['function/bare'] || {};
    return `**${n0(Object.values(m).reduce((a, b) => a + b, 0))}**`;
  })]);
  return table(['Why the graph missed a call written as `f()`', ...groups.map((k) => LABELS[k])], rows);
}

const WRONG = [
  ['callee-not-in-index', 'callee is a function-local constant the compiler index cannot name (unjudged)'],
  ['caller-not-in-index', 'caller is one it cannot name (unjudged)'],
  ['callee-declared-inside-caller', 'callee is declared inside the caller: a nested `def name(` read as a call'],
  ['both-in-index', 'both named by the index, and the compiler found no such call'],
];

function wrong(report) {
  const groups = groupsOf(report);
  const rows = WRONG.map(([id, text]) => [text, ...groups.map((k) => n0(report.groups[k].diagnostics.wrongEdgesByReason[id] || 0))]);
  rows.push(['**graph edges the compiler index lacks**', ...groups.map((k) => `**${n0(Object.values(report.groups[k].diagnostics.wrongEdgesByReason).reduce((a, b) => a + b, 0))}**`)]);
  rows.push(['graph edges between files both sides cover', ...groups.map((k) => n0(rowOf(report.groups[k], 'all edges').precision.n))]);
  return table(['Graph edges the reference does not have', ...groups.map((k) => LABELS[k])], rows);
}

function scope(report) {
  const rows = groupsOf(report).map((k) => {
    const g = report.groups[k];
    const s = g.scope;
    return [LABELS[k], n0(s.universeFiles), n0(s.graphFiles), n0(s.indexedFiles), n0(s.referenceEdges), n0(s.referenceEdgesInU), pct(s.scopeInclusiveRecall), pct(g.fileLevel.precision), pct(g.fileLevel.recall)];
  });
  return table(['Language', 'Files both sides cover', 'Files the graph walked', 'Files indexed', 'Reference edges', 'of them in covered files', 'Recall, scope-inclusive', 'File-pair precision', 'File-pair recall'], rows, ['l']);
}

function registered(report) {
  const t = groupsOf(report).map((k) => {
    const g = report.groups[k];
    return [LABELS[k], g.threshold.recall === null || g.threshold.recall === undefined ? '-' : pct(g.threshold.recall), n0(g.threshold.referenceEdges || 0), g.threshold.status];
  });
  const p = Object.entries(report.predictions).map(([id, v]) => [id, v.claim, v.status, (v.parts || []).filter((x) => x.value !== null && x.value !== undefined && !x.note).map((x) => `${LABELS[x.group]} ${pct(x.value)}`).join(', ') || '-']);
  return [
    table(['Language', 'Receiver-only method recall', 'Reference edges', 'Registered threshold of 70%'], t, ['l']),
    table(['', 'Registered prediction', 'Result', 'Measured'], p, ['l', 'l', 'l']),
  ];
}

/** The generated block, markers included. */
export function renderBlock(report) {
  const [thresholds, predictions] = registered(report);
  const env = report.environment;
  const tools = [`Node ${env.node}`, env.go && `Go ${env.go.go}, scip-go ${env.go.scipGo}`, env.java && `JDK ${env.java.jdk}, scip-java ${env.java.scipJava}, ${env.java.maven}`].filter(Boolean).join('; ');
  const idx = {};
  for (const byRepo of Object.values(report.repos)) for (const r of Object.values(byRepo)) if (r.status === 'measured') idx[r.indexer.split('@')[0]] = r.indexer;
  return [
    BEGIN,
    '',
    `Measured on SigMap ${report.version} (commit \`${report.sigmap.commit.slice(0, 7)}\`), protocol \`${report.protocol.commit.slice(0, 7)}\`, indexers ${Object.values(idx).sort().map((s) => `\`${s}\``).join(', ')}; ${tools}.`,
    '',
    '### Headline',
    '',
    'Recall and precision are over edges between the files both the graph and the compiler index cover. Brackets are 95% cluster-bootstrap intervals over caller files. "Function edges" are calls to a free function; "method edges through a receiver" are `this.m()`, `self.m()`, `x.m()`; a cell with fewer than 100 edges is not quoted.',
    '',
    headline(report),
    '',
    '### By repository',
    '',
    perRepo(report),
    '',
    '### Recall by edge kind and call site',
    '',
    bySite(report),
    '',
    '### Why calls written as `f()` were missed',
    '',
    missed(report),
    '',
    '### Graph edges the reference does not have',
    '',
    wrong(report),
    '',
    '### Scope',
    '',
    scope(report),
    '',
    '### The registered threshold and predictions',
    '',
    thresholds,
    '',
    predictions,
    '',
    END,
  ].join('\n');
}

/** Put the block in a page: replace it between the markers, or return null when they are absent. */
export function inject(page, block) {
  const a = page.indexOf(BEGIN);
  const b = page.indexOf(END);
  if (a === -1 || b === -1 || b < a) return null;
  return page.slice(0, a) + block + page.slice(b + END.length);
}

/** The block as the page holds it, or null. */
export function extract(page) {
  const a = page.indexOf(BEGIN);
  const b = page.indexOf(END);
  return a === -1 || b === -1 ? null : page.slice(a, b + END.length);
}
