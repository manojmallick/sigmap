'use strict';

/**
 * import-accuracy-doc.mjs — the numeric tables of docs-vp/guide/import-accuracy.md, rendered
 * from benchmarks/reports/import-accuracy.json (#980). The page holds this block between two
 * markers and a test regenerates it from the saved report, so a figure on the page cannot differ
 * from the report it quotes. Prose around the block says what the figures mean.
 *
 * Dev-only. Nothing here ships in the npm package.
 */

export const BEGIN = '<!-- import-accuracy:begin (generated by scripts/run-import-accuracy.mjs --write-doc; do not edit) -->';
export const END = '<!-- import-accuracy:end -->';

const LABELS = { c: 'C / C++ / Objective-C', sfc: 'Vue / Svelte / Astro', php: 'PHP', swift: 'Swift (module level)', csharp: 'C#', dart: 'Dart', lua: 'Lua', gdscript: 'GDScript' };
const ORDER = ['c', 'sfc', 'php', 'swift'];
const n0 = (n) => n.toLocaleString('en-US');
const pct = (v) => `${(100 * v).toFixed(1)}%`;

/** `97.2% (95-98)`; `n=40, too few` when the cell has under the protocol's minimum; `-` when empty. */
export function cell(c) {
  if (!c || c.value === null || c.value === undefined) return '-';
  if (c.small) return `n=${n0(c.n)}, too few`;
  const interval = c.lo !== null && c.hi !== null ? ` (${Math.round(100 * c.lo)}-${Math.round(100 * c.hi)})` : '';
  return `${pct(c.value)}${interval}`;
}

const groupsOf = (report) => ORDER.filter((k) => report.groups[k]);

/** A markdown table from a header row and body rows. */
function table(head, rows, align = []) {
  const sep = head.map((_, i) => (align[i] === 'l' || (i === 0 && !align.length) ? '---' : '---:'));
  return [`| ${head.join(' | ')} |`, `|${sep.join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
}

function headline(report) {
  const rows = groupsOf(report).map((k) => {
    const g = report.groups[k];
    return [`**${LABELS[k]}**`, g.repos.join(', '), n0(g.table.recall.n), cell(g.table.recall), n0(g.table.precision.n), cell(g.table.precision), g.table.f1 === null ? '-' : pct(g.table.f1)];
  });
  return table(['Group', 'Repositories', 'Reference edges', 'Recall', 'Graph edges', 'Precision', 'F1'], rows, ['l', 'l']);
}

function perRepo(report) {
  const rows = [];
  for (const k of ORDER) {
    for (const [name, r] of Object.entries(report.repos[k] || {})) {
      if (r.status !== 'measured') {
        rows.push([LABELS[k], name, '`' + r.commit.slice(0, 7) + '`', 'unmeasured', '', '', '', '', r.reason.length > 110 ? `${r.reason.slice(0, 107)}...` : r.reason]);
        continue;
      }
      const c = r.counts;
      rows.push([
        LABELS[k], name, '`' + r.commit.slice(0, 7) + '`', n0(c.universe), n0(c.referenceEdges), n0(c.graphEdges),
        c.graphEdges ? pct(c.truePositives / c.graphEdges) : '-', c.referenceEdges ? pct(c.truePositives / c.referenceEdges) : '-', '',
      ]);
    }
  }
  // the Note column holds why a repository is unmeasured; it is left out when every one was measured
  const noted = rows.some((r) => r[8]);
  const head = ['Group', 'Repository', 'Commit', 'Importing files scored', 'Reference edges', 'Graph edges', 'Precision', 'Recall'];
  if (!noted) return table(head, rows.map((r) => r.slice(0, 8)), ['l', 'l', 'l']);
  return table([...head, 'Note'], rows, ['l', 'l', 'l', 'r', 'r', 'r', 'r', 'r', 'l']);
}

function scope(report) {
  const rows = [];
  for (const k of ORDER) {
    for (const [name, r] of Object.entries(report.repos[k] || {})) {
      if (r.status !== 'measured') continue;
      const c = r.counts;
      rows.push([LABELS[k], name, n0(c.walked), n0(c.covered), n0(c.universe), n0(c.graphEdgesOutsideUniverse), n0(c.referenceEdgesOutsideUniverse)]);
    }
  }
  return table(['Group', 'Repository', 'Files the graph walked', 'Files the reference could analyse', 'Scored (both)', 'Graph edges outside', 'Reference edges outside'], rows, ['l', 'l']);
}

/** Counts of edges by kind, one column per group; null when no group carries diagnostics. */
function kinds(report, key, title) {
  const groups = groupsOf(report).filter((k) => report.groups[k].diagnostics);
  const total = (kind) => groups.reduce((n, k) => n + (report.groups[k].diagnostics[key][kind] || 0), 0);
  const all = [...new Set(groups.flatMap((k) => Object.keys(report.groups[k].diagnostics[key])))].sort((a, b) => total(b) - total(a) || a.localeCompare(b));
  if (!all.length) return null;
  const rows = all.map((kind) => [kind, ...groups.map((k) => n0(report.groups[k].diagnostics[key][kind] || 0))]);
  rows.push(['**all**', ...groups.map((k) => `**${n0(Object.values(report.groups[k].diagnostics[key]).reduce((a, b) => a + b, 0))}**`)]);
  return table([title, ...groups.map((k) => LABELS[k])], rows, ['l']);
}

/** Which repository the missed edges are in, and how their imports reach the file. */
function whereMissed(report) {
  const rows = [];
  for (const k of ORDER) {
    for (const [name, r] of Object.entries(report.repos[k] || {})) {
      if (r.status !== 'measured' || !r.diagnostics) continue;
      for (const [kind, n] of Object.entries(r.diagnostics.missedByKind).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))) rows.push([LABELS[k], name, kind, n0(n)]);
    }
  }
  return rows.length ? table(['Group', 'Repository', 'How the missed import reaches its file', 'Reference edges missed'], rows, ['l', 'l', 'l']) : null;
}

function unmeasured(report) {
  const rows = [];
  for (const [k, why] of Object.entries(report.unregistered || {})) rows.push([LABELS[k] || k, 'language', why]);
  for (const [k, why] of Object.entries(report.unmeasured || {})) rows.push([k, 'repository', why.length > 160 ? `${why.slice(0, 157)}...` : why]);
  return rows.length ? table(['What', 'Kind', 'Why there is no figure'], rows, ['l', 'l', 'l']) : null;
}

function predictions(report) {
  const rows = Object.entries(report.predictions).map(([id, v]) => [id, v.claim, v.status, v.value === null || v.value === undefined ? '-' : pct(v.value)]);
  return table(['', 'Registered prediction', 'Result', 'Measured'], rows, ['l', 'l', 'l']);
}

/** The generated block, markers included. */
export function renderBlock(report) {
  const env = report.environment;
  const tools = Object.values(report.groups).map((g) => g.reference).filter(Boolean);
  const blocks = [
    BEGIN,
    '',
    `Measured on SigMap ${report.version} (commit \`${report.sigmap.commit.slice(0, 7)}\`), protocol \`${report.protocol.commit.slice(0, 7)}\`; Node ${env.node} on ${env.platform}. References: ${[...new Set(tools)].map((t) => `\`${t}\``).join('; ') || 'none'}.`,
    '',
    '### Headline',
    '',
    'Precision and recall are over edges whose importing file both the graph and the reference read. Brackets are 95% cluster-bootstrap intervals over importing files; a cell with fewer than 100 edges is not quoted.',
    '',
    headline(report),
    '',
    '### By repository',
    '',
    perRepo(report),
    '',
    '### Scope',
    '',
    scope(report),
    '',
  ];
  const missed = kinds(report, 'missedByKind', 'Reference edges the graph lacks, by how the import reaches its file');
  const wrong = kinds(report, 'wrongByKind', 'Graph edges the reference lacks, by what they reach');
  const where = whereMissed(report);
  if (missed) blocks.push('### Why edges were missed', '', missed, '');
  if (where) blocks.push('### Where the missed edges are', '', where, '');
  if (wrong) blocks.push('### Graph edges the reference does not have', '', wrong, '');
  const un = unmeasured(report);
  if (un) blocks.push('### Not measured', '', un, '');
  blocks.push('### The registered predictions', '', predictions(report), '', END);
  return blocks.join('\n');
}

/** Put the block in a page: replace it between the markers, or return null when they are absent. */
export function inject(page, block) {
  const a = page.indexOf(BEGIN);
  const b = page.indexOf(END);
  if (a === -1 || b === -1 || b < a) return null;
  return page.slice(0, a) + block + page.slice(b + END.length);
}

/** The block as the page holds it, or null. */
export function extract(page) {
  const a = page.indexOf(BEGIN);
  const b = page.indexOf(END);
  return a === -1 || b === -1 ? null : page.slice(a, b + END.length);
}
